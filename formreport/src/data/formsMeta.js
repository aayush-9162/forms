export function getFormsByCategory() {
  const grouped = {}
  for (const category of CATEGORIES) grouped[category.key] = []
  for (const [key, meta] of Object.entries(FORMS_META)) {
    const cat = meta.category || 'General'
    if (!grouped[cat]) grouped[cat] = []
    grouped[cat].push({ key, ...meta })
  }
  return grouped
}
